const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const context={};vm.createContext(context);vm.runInContext(fs.readFileSync(require('node:path').join(__dirname, '..', 'engine.js'),'utf8'),context);
let now=Date.UTC(2026,9,19,12), data;
const storage={getItem:()=>data,setItem:(_,value)=>data=value};
const game=context.AetheriaEngine.createGame({storage,now:()=>now,random:()=>.1});
for(let i=0;i<3;i++) game.dispatch('adventure');
assert(game.dispatch('claimQuest',{questId:'daily-adventure'}).ok);
assert.equal(game.getState().stats.adventures,5);
now+=86400000;
const restored=context.AetheriaEngine.createGame({storage,now:()=>now,random:()=>.1});
assert.equal(restored.getState().daily.adventures,0);
assert.equal(restored.getState().stats.adventures,5);
assert.equal(restored.getState().quests[0].claimed,false);
assert.equal(restored.getState().quests[0].progress,0);
assert(!restored.dispatch('claimQuest',{questId:'daily-adventure'}).ok);
for(let i=0;i<5;i++) restored.dispatch('adventure');
assert(restored.dispatch('claimQuest',{questId:'daily-adventure'}).ok);
assert.equal(restored.getState().stats.adventures,10);
now+=86400000;
assert(restored.dispatch('adventure').ok);
assert.equal(restored.getState().daily.adventures,1);
assert.equal(restored.getState().quests[0].progress,1);
assert.equal(restored.getState().quests[0].claimed,false);
console.log('PASS: daily quest rollover on reload and in-session actions; lifetime achievement counters preserved.');
