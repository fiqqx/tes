const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = { Math, Date, Set, Object, JSON, Number, String, TypeError, globalThis: {} };
vm.runInNewContext(fs.readFileSync(require('node:path').join(__dirname, '..', 'engine.js'), 'utf8'), context);
const Engine = context.globalThis.AetheriaEngine;
let roll = 0.2;
const storageData = new Map();
const storage = { getItem: key => storageData.get(key) || null, setItem: (key,value) => storageData.set(key,value) };
const game = Engine.createGame({storage, random: () => roll, now: () => 123456});
let notifications = 0;
const unsub = game.subscribe(() => notifications++);
const initial = game.getState();
assert.equal(initial.player.name, 'Aerin');
assert.equal(initial.equipment.length, 6);
assert(Object.isFrozen(initial.player));
assert.equal(initial, game.getState());
assert(!game.dispatch('refine', {itemId: 'bad'}).ok);
assert.equal(game.getState(), initial);
let info = game.getRefineInfo('weapon', true);
assert.equal(info.successRate, 75);
assert.equal(info.material, 'oridecon');
let result = game.dispatch('refine', {itemId:'weapon'});
assert(result.success);
assert.equal(game.getState().equipment[0].refine, 5);
assert.equal(game.getState().materials.oridecon, initial.materials.oridecon - info.materialCost);
assert.equal(game.getState().currencies.zeny, initial.currencies.zeny - info.cost);
assert(game.getState().player.power > initial.player.power);
assert.equal(initial.equipment[0].refine, 4);
roll = 0.99;
result = game.dispatch('refine', {itemId:'weapon', useProtection:true});
assert(!result.success && result.protected && !result.downgraded);
assert.equal(game.getState().equipment[0].refine, 5);
assert.equal(game.getState().materials.protection, 4);
result = game.dispatch('refine', {itemId:'weapon'});
assert(result.downgraded);
assert.equal(game.getState().equipment[0].refine, 4);
assert(game.getState().quests.find(x => x.id==='daily-refine').claimable);
assert(game.dispatch('claimQuest',{questId:'daily-refine'}).ok);
assert(!game.dispatch('claimQuest',{questId:'daily-refine'}).ok);
assert(game.dispatch('claimAchievement',{achievementId:'first-refine'}).ok);
assert(!game.dispatch('buy',{itemId:'potion',quantity:-1}).ok);
assert(!game.dispatch('buy',{itemId:'potion',quantity:1.5}).ok);
const beforeBuy = game.getState();
assert(game.dispatch('buy',{itemId:'potion',quantity:3}).ok);
assert.equal(game.getState().materials.potion,beforeBuy.materials.potion+3);
assert.equal(game.getState().currencies.zeny,beforeBuy.currencies.zeny-5400);
roll = 0.4;
assert(!game.dispatch('adventure',{regionId:'tundra'}).ok);
for(let i=0;i<3;i++) assert(game.dispatch('adventure',{regionId:'forest'}).ok);
assert(game.getState().player.level > initial.player.level);
assert(game.dispatch('claimQuest',{questId:'daily-adventure'}).ok);
const beforeMail = game.getState().currencies.crystals;
assert(game.dispatch('claimMail').ok);
assert.equal(game.getState().currencies.crystals,beforeMail+300);
assert(!game.dispatch('claimMail').ok);
const beforeGuild = game.getState();
assert(game.dispatch('contributeGuild').ok);
assert.equal(game.getState().guild.contribution,beforeGuild.guild.contribution+100);
assert.equal(game.getState().currencies.zeny,beforeGuild.currencies.zeny-10000);
assert(game.dispatch('rename',{name:'  Test Knight  '}).ok);
assert.equal(game.getState().player.name,'Test Knight');
assert(!game.dispatch('rename',{name:'   '}).ok);
assert(game.dispatch('startBoss',{bossId:'verdant'}).ok);
assert(!game.dispatch('adventure',{regionId:'forest'}).ok);
assert(!game.dispatch('startBoss',{bossId:'frost'}).ok);
assert(!game.dispatch('attackBoss',{skillId:'heal'}).ok);
assert(game.dispatch('attackBoss',{skillId:'cleave'}).ok);
const beforeCooldown = game.getState();
assert(!game.dispatch('attackBoss',{skillId:'cleave'}).ok);
assert.equal(game.getState(),beforeCooldown);
assert(game.dispatch('attackBoss',{skillId:'heal'}).ok);
assert(game.getState().combat.cooldowns.heal>0);
const restored = Engine.createGame({storage,random:()=>roll});
assert.equal(restored.getState().player.name,'Test Knight');
assert.equal(restored.getState().combat.turn,game.getState().combat.turn);
assert.equal(restored.getState().combat.cooldowns.heal,game.getState().combat.cooldowns.heal);
let actions = 0;
while(game.getState().combat.active && actions++<35) {
 const combat=game.getState().combat;
 const skill=combat.playerHp < game.getState().player.maxHp*.45 && !combat.cooldowns.heal ? 'heal' : !combat.cooldowns.cleave ? 'cleave':'slash';
 assert(game.dispatch('attackBoss',{skillId:skill}).ok);
}
assert(game.getState().combat.won);
assert.equal(game.getState().stats.bossKills,1);
assert(game.dispatch('claimQuest',{questId:'daily-mvp'}).ok);
const afterVictory=game.getState();
assert(!game.dispatch('attackBoss',{skillId:'slash'}).ok);
assert.equal(game.getState(),afterVictory);
assert(game.dispatch('closeCombat').ok);
assert.equal(game.getState().combat,null);
assert.equal(game.getState().player.hp,game.getState().player.maxHp);
assert(game.dispatch('startBoss',{bossId:'frost'}).ok);
for(let i=0;game.getState().combat.active && i<40;i++) game.dispatch('attackBoss',{skillId:'slash'});
assert(game.getState().combat.lost);
assert(game.dispatch('fleeBoss').ok);
assert(game.dispatch('startBoss',{bossId:'verdant'}).ok);
assert(game.dispatch('fleeBoss').ok);
assert.equal(game.getState().combat,null);
const beforeUnsub=notifications; unsub(); game.dispatch('buy',{itemId:'potion'}); assert.equal(notifications,beforeUnsub);
const badStorage={getItem:()=>'{invalid',setItem:()=>{throw Error('quota')}};
const fallback=Engine.createGame({storage:badStorage});
assert.equal(fallback.getState().player.name,'Aerin');
assert(fallback.dispatch('claimMail').ok);
const maxSave=JSON.parse(storageData.get(Engine.saveKey)); maxSave.equipment[0].refine=15;
const maxGame=Engine.createGame({storage:{getItem:()=>JSON.stringify(maxSave),setItem:()=>{}}});
assert.equal(maxGame.getRefineInfo('weapon').successRate,0);
assert(!maxGame.dispatch('refine',{itemId:'weapon'}).ok);
assert(game.reset().ok);
assert.equal(game.getState().player.level,28);
assert.equal(game.getState().stats.bossKills,0);
console.log('PASS: refine success/failure/protection, prices, stats, progression, quest/achievement/mail single claims, guild, rename, combat skills/cooldowns/healing/victory/defeat/flee, persistence, invalid storage, immutable snapshots, subscribers, and reset.');
